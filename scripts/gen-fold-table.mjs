// Writes what the phone needs to fold text the way the web does (src/lib/fold.js), since Dart has no
// Unicode normalisation of its own:
//
//   android_app/lib/utils/fold_table.dart        the table the phone's fold() reads
//   android_app/test/fixtures/fold_cases.txt     every character the web changes, and what it becomes,
//                                                which the phone's tests check one by one
//
//   node scripts/gen-fold-table.mjs
//
// tests/fold-table.test.mjs fails when either file is out of date, so a change to fold.js cannot go in
// without running this.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { fold } from '../src/lib/fold.js'

const MARK = /^\p{M}$/u
const hex = (n) => '0x' + n.toString(16)
const chars = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  chars.push([cp, String.fromCodePoint(cp)])
}

// "\u{e9}" for anything that is not a plain letter or digit, so the file is the same in any editor.
const dartString = (s) => `'${[...s].map((c) => (/[a-z0-9]/.test(c) ? c : `\\u{${c.codePointAt(0).toString(16)}}`)).join('')}'`

/** The text of lib/utils/fold_table.dart. */
export function foldTableSource() {
  const lines = []
  for (const [cp, ch] of chars) {
    if (cp < 0x80 || MARK.test(ch)) continue // ASCII is done by the phone itself; marks are the ranges below
    const f = fold(ch)
    if (f !== ch) lines.push(`  ${hex(cp)}: ${dartString(f)},`)
  }
  const ranges = []
  let from = -1
  let prev = -2
  for (const [cp, ch] of chars) {
    if (!MARK.test(ch)) continue
    if (cp === prev + 1 && from >= 0) { prev = cp; continue }
    if (from >= 0) ranges.push(`${hex(from)}, ${hex(prev)},`)
    from = cp
    prev = cp
  }
  ranges.push(`${hex(from)}, ${hex(prev)},`)
  const rows = []
  for (let i = 0; i < ranges.length; i += 4) rows.push('  ' + ranges.slice(i, i + 4).join(' '))
  return [
    '// GENERATED by scripts/gen-fold-table.mjs from src/lib/fold.js. Do not edit by hand:',
    '// run `node scripts/gen-fold-table.mjs` (tests/fold-table.test.mjs fails when this is out of date).',
    '',
    '/// What each character beyond ASCII is folded to (lower case, no accent: "É" is "e", "ß" is "ss"): every',
    '/// one the web changes, capitals included, so the phone does not depend on its own (older) Unicode data.',
    '/// A character that is not here stays as it is.',
    'const Map<int, String> foldTable = {',
    ...lines,
    '};',
    '',
    '/// The marks (Unicode category M), as first and last code point, in order: these fold to nothing.',
    'const List<int> foldMarkRanges = [',
    ...rows,
    '];',
    '',
  ].join('\n')
}

/** The text of test/fixtures/fold_cases.txt: `code point <TAB> what it folds to` (both in hex), for every one that changes. */
export function foldCasesSource() {
  const out = ['# GENERATED by scripts/gen-fold-table.mjs: every character the web folds to something else (code point, tab, the code points it becomes; none = nothing).']
  for (const [cp, ch] of chars) {
    const f = fold(ch)
    if (f === ch) continue
    out.push(`${cp.toString(16)}\t${[...f].map((c) => c.codePointAt(0).toString(16)).join(' ') || 'none'}`)
  }
  return out.join('\n') + '\n'
}

export const TABLE_PATH = 'android_app/lib/utils/fold_table.dart'
export const CASES_PATH = 'android_app/test/fixtures/fold_cases.txt'

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  const crlf = (s) => s.replace(/\n/g, '\r\n') // like the files around them
  fs.mkdirSync(path.join(root, path.dirname(CASES_PATH)), { recursive: true })
  fs.writeFileSync(path.join(root, TABLE_PATH), crlf(foldTableSource()))
  fs.writeFileSync(path.join(root, CASES_PATH), foldCasesSource())
  console.log('wrote', TABLE_PATH, 'and', CASES_PATH)
}
